"""Writes assets/dial.usda: the turnable dial, an articulation with one revolute joint.

    python tasks/dial-match/make_dial_usda.py

Structure follows the hinged platform in tasks/lock-before-loading (converted from URDF there, hand-built here):
a fixed base link with the articulation root, pinned to the world by a fixed joint, and a child link (the knob) on a
revolute joint about the base's z axis, limits in degrees. The base plate, ticks and knob are USD primitives
(Cylinder, Cube) with displayColor, as in lock-before-loading/assets/pin.usda. Ticks and the pointer tip are visual only.
"""

import math
from pathlib import Path

import geometry as g

OUT = Path(__file__).resolve().parent / "assets" / "dial.usda"


def _f(v):
    return f"{v:.6g}"


def _vec(v):
    return "(" + ", ".join(_f(x) for x in v) + ")"


def _cube(name, size, translate, color, orient_wxyz=(1.0, 0.0, 0.0, 0.0), collide=True, indent=8):
    pad = " " * indent
    api = '\n' + pad + '    prepend apiSchemas = ["PhysicsCollisionAPI"]' if collide else ""
    head = f'{pad}def Cube "{name}"' + (f" ({api}\n{pad})" if collide else "")
    return (
        f"{head}\n{pad}{{\n"
        f"{pad}    color3f[] primvars:displayColor = [{_vec(color)}]\n"
        f"{pad}    double size = 1\n"
        f"{pad}    double3 xformOp:translate = {_vec(translate)}\n"
        f"{pad}    quatf xformOp:orient = {_vec(orient_wxyz)}\n"
        f"{pad}    float3 xformOp:scale = {_vec(size)}\n"
        f'{pad}    uniform token[] xformOpOrder = ["xformOp:translate", "xformOp:orient", "xformOp:scale"]\n'
        f"{pad}}}\n"
    )


def build() -> str:
    ticks = ""
    for deg in g.TICK_DEG:
        a = math.radians(deg)
        ticks += _cube(f"tick_{deg:03d}", g.TICK, (g.TICK_R * math.cos(a), g.TICK_R * math.sin(a), g.PLATE_H + g.TICK[2] / 2),
                       g.TICK_COLOR, g.yaw_quat_wxyz(deg), collide=False, indent=12)
    knob_z = g.PLATE_H  # the knob link's origin sits on the plate's top face, on the axis
    bar = _cube("bar", g.BAR, (0.0, 0.0, g.BAR_CZ - knob_z), g.KNOB_COLOR, indent=16)
    tip = _cube("tip", g.TIP, (g.TIP_CX, 0.0, g.TIP_CZ - knob_z), g.TIP_COLOR, collide=False, indent=16)
    return f'''#usda 1.0
(
    doc = "Generated by make_dial_usda.py; do not edit by hand."
    defaultPrim = "dial"
    kilogramsPerUnit = 1
    metersPerUnit = 1
    upAxis = "Z"
)

def Xform "dial"
{{
    def Xform "Geometry"
    {{
        def Xform "base" (
            prepend apiSchemas = ["PhysicsRigidBodyAPI", "PhysicsArticulationRootAPI", "PhysicsMassAPI"]
        )
        {{
            float physics:mass = {_f(g.BASE_MASS)}

            def Cylinder "plate" (
                prepend apiSchemas = ["PhysicsCollisionAPI"]
            )
            {{
                uniform token axis = "Z"
                double height = {_f(g.PLATE_H)}
                double radius = {_f(g.PLATE_R)}
                color3f[] primvars:displayColor = [{_vec(g.PLATE_COLOR)}]
                double3 xformOp:translate = (0, 0, {_f(g.PLATE_H / 2)})
                uniform token[] xformOpOrder = ["xformOp:translate"]
            }}

{ticks}
            def Xform "knob" (
                prepend apiSchemas = ["PhysicsRigidBodyAPI", "PhysicsMassAPI"]
            )
            {{
                float physics:mass = {_f(g.KNOB_MASS)}
                double3 xformOp:translate = (0, 0, {_f(knob_z)})
                uniform token[] xformOpOrder = ["xformOp:translate"]

{bar}
{tip}            }}
        }}
    }}

    def Scope "Physics"
    {{
        def PhysicsRevoluteJoint "{g.JOINT}" (
            prepend apiSchemas = ["PhysicsDriveAPI:angular"]
        )
        {{
            float drive:angular:physics:damping = 0.0005
            float drive:angular:physics:maxForce = 100
            float drive:angular:physics:stiffness = 0
            uniform token drive:angular:physics:type = "force"
            uniform token physics:axis = "Z"
            rel physics:body0 = </dial/Geometry/base>
            rel physics:body1 = </dial/Geometry/base/knob>
            point3f physics:localPos0 = (0, 0, {_f(knob_z)})
            point3f physics:localPos1 = (0, 0, 0)
            quatf physics:localRot0 = (1, 0, 0, 0)
            quatf physics:localRot1 = (1, 0, 0, 0)
            float physics:lowerLimit = {_f(g.LOWER_DEG)}
            float physics:upperLimit = {_f(g.UPPER_DEG)}
        }}

        def PhysicsFixedJoint "root_joint"
        {{
            rel physics:body0 = </dial>
            rel physics:body1 = </dial/Geometry/base>
            point3f physics:localPos0 = (0, 0, 0)
            point3f physics:localPos1 = (0, 0, 0)
            quatf physics:localRot0 = (1, 0, 0, 0)
            quatf physics:localRot1 = (1, 0, 0, 0)
        }}
    }}
}}
'''


if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(build())
    print(f"wrote {OUT}")
